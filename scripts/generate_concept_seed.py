"""Generate a reviewable SQL seed from the canonical supplied concept CSV."""
import csv
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
COLUMNS=['concept_id','name','category','definition','acceptable_extensions','dict_content','key_terms','defense_prompt']

def quote(value):
    return "'" + value.replace("'", "''") + "'"

def generate(source):
    rows=list(csv.DictReader(source.open(encoding='utf-8',newline='')))
    if not rows or set(rows[0])!=set(COLUMNS): raise ValueError('Unexpected concept columns')
    ids=set();names=set();values=[]
    for row in rows:
        identity=int(row['concept_id'])
        if identity<=0 or identity in ids or not row['name'] or row['name'] in names:
            raise ValueError('Invalid or duplicate concept identity')
        ids.add(identity);names.add(row['name'])
        fields=[str(identity)]+[quote(row[c]) + ('::text[]' if c=='key_terms' else '') for c in COLUMNS[1:]]
        values.append('('+', '.join(fields)+')')
    return '''-- Generated by scripts/generate_concept_seed.py from user-supplied data.
BEGIN;
CREATE TEMP TABLE imported_concepts (LIKE public.concepts INCLUDING DEFAULTS) ON COMMIT DROP;
INSERT INTO imported_concepts ('''+', '.join(COLUMNS)+') VALUES\n'+',\n'.join(values)+''';
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM imported_concepts i JOIN public.concepts c
      ON i.concept_id=c.concept_id OR i.name=c.name
      WHERE i.concept_id<>c.concept_id OR i.name<>c.name) THEN
        RAISE EXCEPTION 'Concept ID/name collision: import into a fresh database or reconcile explicitly';
    END IF;
END $$;
INSERT INTO public.concepts ('''+', '.join(COLUMNS)+')\nSELECT '+', '.join(COLUMNS)+''' FROM imported_concepts ON CONFLICT DO NOTHING;
SELECT setval(pg_get_serial_sequence('public.concepts','concept_id'),
    GREATEST((SELECT max(concept_id) FROM public.concepts),
             (SELECT last_value FROM public.concepts_concept_id_seq)), true);
COMMIT;
'''

if __name__=='__main__':
    (ROOT/'supabase/seed/concepts.sql').write_text(generate(ROOT/'supabase/seed/concepts.csv'),encoding='utf-8')
