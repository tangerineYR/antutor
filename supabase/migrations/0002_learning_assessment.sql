ALTER TABLE public.sessions ADD COLUMN hakes_gain double precision;
-- Application uses user_attendance, not attendance.
CREATE TABLE public.user_attendance (
    user_id uuid NOT NULL REFERENCES public.users ON DELETE CASCADE,
    attendance_date date NOT NULL,
    PRIMARY KEY (user_id, attendance_date)
);

CREATE TABLE public.questions (
    question_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept_id bigint REFERENCES public.concepts ON DELETE CASCADE,
    question_text text NOT NULL,
    option_1 text NOT NULL, option_2 text NOT NULL, option_3 text NOT NULL,
    option_4 text NOT NULL, option_5 text NOT NULL,
    correct_option integer NOT NULL CHECK (correct_option BETWEEN 1 AND 5),
    commentary text NOT NULL DEFAULT ''
);
CREATE TABLE public.quiz_attempts (
    attempt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint REFERENCES public.sessions ON DELETE CASCADE,
    user_id uuid NOT NULL REFERENCES public.users ON DELETE CASCADE,
    quiz_type text NOT NULL CHECK (quiz_type IN ('PRE', 'POST')),
    total_score integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX quiz_attempts_session_type_idx ON public.quiz_attempts (session_id, quiz_type, created_at DESC);
CREATE TABLE public.quiz_answers (
    answer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id bigint NOT NULL REFERENCES public.quiz_attempts ON DELETE CASCADE,
    question_id bigint NOT NULL REFERENCES public.questions ON DELETE CASCADE,
    selected_option integer NOT NULL CHECK (selected_option BETWEEN 1 AND 6),
    confidence_level integer NOT NULL CHECK (confidence_level BETWEEN 0 AND 3),
    is_correct boolean NOT NULL,
    earned_score integer NOT NULL,
    CONSTRAINT quiz_uncertainty_pair CHECK ((selected_option = 6) = (confidence_level = 0)),
    CONSTRAINT quiz_uncertainty_score CHECK (selected_option <> 6 OR (NOT is_correct AND earned_score = 0)),
    UNIQUE (attempt_id, question_id)
);
