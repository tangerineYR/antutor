-- Fresh-database baseline inferred from application contracts, not a live DB dump.
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE TABLE public.users (
    user_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    username text NOT NULL UNIQUE CHECK (username ~ '^[A-Za-z0-9]{4,}$'),
    password_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.concepts (
    concept_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE,
    definition text NOT NULL,
    acceptable_extensions text NOT NULL DEFAULT '',
    dict_content text NOT NULL DEFAULT '',
    category text NOT NULL DEFAULT 'academic',
    key_terms text[] NOT NULL DEFAULT '{}',
    defense_prompt text NOT NULL DEFAULT ''
);
CREATE TABLE public.sessions (
    session_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.users ON DELETE CASCADE,
    concept_id bigint NOT NULL REFERENCES public.concepts ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS', 'ENDED')),
    idk_count integer NOT NULL DEFAULT 0 CHECK (idk_count BETWEEN 0 AND 3),
    scaffolding_counter integer NOT NULL DEFAULT 0 CHECK (scaffolding_counter >= 0),
    consecutive_high_score_count integer NOT NULL DEFAULT 0 CHECK (consecutive_high_score_count >= 0),
    source_turn_count integer NOT NULL DEFAULT 0 CHECK (source_turn_count >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessions_learner_concept_idx ON public.sessions (user_id, concept_id, created_at DESC);
CREATE TABLE public.chat_logs (
    log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES public.sessions ON DELETE CASCADE,
    turn_number integer NOT NULL CHECK (turn_number > 0),
    user_message text NOT NULL,
    ai_response text NOT NULL,
    score_academic double precision NOT NULL DEFAULT 0,
    score_market double precision NOT NULL DEFAULT 0,
    score_macro double precision NOT NULL DEFAULT 0,
    selected_agent text,
    scaffold_step text,
    news_urls jsonb NOT NULL DEFAULT '[]'::jsonb,
    turn_summary text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX chat_logs_session_turn_idx ON public.chat_logs (session_id, turn_number);
