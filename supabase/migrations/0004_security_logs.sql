CREATE TABLE public.security_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid REFERENCES public.users ON DELETE SET NULL,
    threat_type text NOT NULL CHECK (threat_type IN ('prompt_injection', 'jailbreak', 'harmful_content')),
    transport text NOT NULL CHECK (transport IN ('rest', 'websocket')),
    created_at timestamptz NOT NULL DEFAULT now()
);
-- No learner text, passwords, tokens or matched excerpts belong in this table.
CREATE INDEX security_logs_user_time_idx ON public.security_logs (user_id, created_at DESC);
CREATE INDEX security_logs_type_time_idx ON public.security_logs (threat_type, created_at DESC);
