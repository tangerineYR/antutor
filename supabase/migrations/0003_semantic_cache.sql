CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;
CREATE TABLE public.semantic_cache (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concept text NOT NULL,
    last_question text NOT NULL DEFAULT '',
    namespace text UNIQUE CHECK (namespace ~ '^[a-f0-9]{64}$'),
    user_answer text NOT NULL,
    cached_response text NOT NULL,
    embedding public.vector(384) NOT NULL,
    hit_count bigint NOT NULL DEFAULT 0 CHECK (hit_count >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX semantic_cache_expiry_idx ON public.semantic_cache (created_at);
-- Namespace is unique: exact B-tree lookup examines at most one vector. An ANN
-- index is counterproductive here. Do not install an unbenchmarked lists=100.
CREATE FUNCTION public.match_semantic_cache_v2(
    p_concept text, p_last_question text, p_namespace text, p_embedding public.vector(384),
    p_match_threshold double precision DEFAULT 0.98, p_match_count integer DEFAULT 1,
    p_record_hit boolean DEFAULT false
) RETURNS TABLE(id bigint, cached_response text, similarity double precision)
LANGUAGE plpgsql SECURITY INVOKER SET search_path = public, pg_temp AS $$
BEGIN
    IF p_namespace IS NULL OR p_namespace = '' OR p_match_count < 1 THEN RETURN; END IF;
    IF p_match_threshold < 0 OR p_match_threshold > 1 THEN
        RAISE EXCEPTION 'Invalid similarity threshold';
    END IF;
    IF p_record_hit THEN
        RETURN QUERY
        UPDATE public.semantic_cache c SET hit_count = c.hit_count + 1
        WHERE c.namespace = p_namespace AND c.concept = p_concept
          AND c.last_question = p_last_question AND c.created_at > now() - interval '24 hours'
          AND 1 - (c.embedding <=> p_embedding) >= p_match_threshold
        RETURNING c.id, c.cached_response, 1 - (c.embedding <=> p_embedding);
    ELSE
        RETURN QUERY SELECT c.id, c.cached_response, 1 - (c.embedding <=> p_embedding)
        FROM public.semantic_cache c
        WHERE c.namespace = p_namespace AND c.concept = p_concept
          AND c.last_question = p_last_question AND c.created_at > now() - interval '24 hours'
          AND 1 - (c.embedding <=> p_embedding) >= p_match_threshold
        LIMIT LEAST(p_match_count, 1);
    END IF;
END;
$$;
-- Preserve the legacy API for controlled migration of existing installations.
-- The new application never calls this unscoped function or reads legacy rows.
CREATE FUNCTION public.match_semantic_cache(
    p_concept text, p_last_question text, p_embedding public.vector(384),
    p_match_threshold double precision DEFAULT 0.65, p_match_count integer DEFAULT 1
) RETURNS TABLE(id bigint, cached_response text, similarity double precision)
LANGUAGE sql STABLE SECURITY INVOKER SET search_path = public, pg_temp AS $$
    SELECT c.id, c.cached_response, 1 - (c.embedding <=> p_embedding)
    FROM public.semantic_cache c
    WHERE c.namespace IS NULL AND c.concept = p_concept AND c.last_question = p_last_question
      AND 1 - (c.embedding <=> p_embedding) >= p_match_threshold
    ORDER BY c.embedding <=> p_embedding LIMIT GREATEST(0, LEAST(p_match_count, 100));
$$;
